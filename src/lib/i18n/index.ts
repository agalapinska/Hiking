export type Key = keyof (typeof dict)['pl'];

const initial: Lang = browser
	? ((localStorage.getItem('lang') as Lang) ?? (navigator.language.startsWith('pl') ? 'pl' : 'en'))
	: 'pl';

export const lang = writable<Lang>(initial);
if (browser) lang.subscribe((l) => localStorage.setItem('lang', l));

export const t = derived(lang, ($lang) => (key: Key, vars?: Record<string, string | number>) => {
	let s: string = dict[$lang][key] ?? dict.pl[key] ?? key;
	if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
	return s;
});
